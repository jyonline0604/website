    content = '\n'.join(content_lines)
    
    # 去除重複段落 - 找常見的重複模式並清理
    # 這裡我們簡單處理：如果連續5行以上相同，則去除重複
    
    final_lines = []
    prev_line = None
    repeat_count = 0
    
    for line in content.split('\n'):
        if line == prev_line and len(line) < 100:
            repeat_count += 1
            if repeat_count <= 1:  # 允許第一次重複
                final_lines.append(line)
        else:
            repeat_count = 0
            final_lines.append(line)
        prev_line = line
    
    cleaned_content = '\n'.join(final_lines)
    
    return title_line, cleaned_content


